import { expect, test } from "@playwright/test";
import { collectConsoleErrors } from "./helpers";

// End-to-end AI funnel against the deterministic mock provider
// (AI_PROVIDER=mock is injected by playwright.config.ts's webServer). This is
// the P0 product path: homepage prompt → generation → editor scene → edit →
// device preview → export.

const ANIME_HUD_PROMPT =
  "Create an anime battleground HUD with health, stamina, four skills and an ultimate meter.";

test("@smoke prompt → working editable GUI → edit → preview → export", async ({
  page,
}) => {
  const consoleErrors = collectConsoleErrors(page);

  await page.goto("/");
  await page
    .getByLabel("Describe your Roblox GUI")
    .fill(ANIME_HUD_PROMPT);
  await page.getByRole("button", { name: "Generate GUI" }).click();

  // Lands in the editor with the AI bar and the funnel param stripped.
  await page.waitForURL(/\/editor(\?generated=1)?$/);
  await expect(page.getByText(/AI-generated · hud/)).toBeVisible();
  await page.waitForURL(/\/editor$/);

  // The composed scene is real: component tree shows the generated nodes.
  await page.getByRole("button", { name: "Hierarchy" }).click();
  await expect(
    page.locator('[role="treeitem"]', { hasText: "HealthBarFill" })
  ).toBeVisible();
  await expect(
    page.locator('[role="treeitem"]', { hasText: "SkillBar" })
  ).toBeVisible();
  await expect(
    page.locator('[role="treeitem"]', { hasText: "UltimateFill" })
  ).toBeVisible();

  // Client + server Luau render in the code panel.
  await expect(page.getByLabel("Client Luau code")).toContainText(
    "-- Generated by Roblox GUI Maker"
  );
  await expect(page.getByLabel("Client Luau code")).toContainText("StatsPanel");

  // First edit: select a node and nudge it (keyboard path).
  await page.locator('[data-node-id]').first().click();
  await page.keyboard.press("ArrowRight");

  // Responsive preview switch works on the generated scene.
  await page.getByRole("button", { name: "Tablet" }).click();
  await page.getByRole("button", { name: "Mobile" }).click();
  await page.getByRole("button", { name: "Desktop" }).click();

  // Export: the ZIP download fires.
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download ZIP" }).click();
  expect((await download).suggestedFilename()).toMatch(/\.zip$/);

  // Regenerate keeps the editor in a working state.
  await page.getByRole("button", { name: "Regenerate" }).click();
  await expect(page.getByText(/AI-generated · hud/)).toBeVisible();

  expect(consoleErrors).toEqual([]);
});

