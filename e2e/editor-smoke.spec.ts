import { expect, test } from "@playwright/test";
import { collectConsoleErrors } from "./helpers";

test("@smoke keeps initially hidden layers off the canvas until selected", async ({
  page,
}) => {
  await page.goto("/editor?template=main-menu");

  const settingsPanel = page.locator('[data-node-id="tpl-4"]');
  await expect(settingsPanel).toHaveCount(0);

  await page.getByRole("button", { name: "Hierarchy" }).click();
  await page.locator('[data-tree-node="tpl-4"] > [role="treeitem"]').click();
  await expect(settingsPanel).toBeVisible();

  await page.locator('[data-tree-node="tpl-7"] > [role="treeitem"]').click();
  await expect(settingsPanel).toBeVisible();
  await expect(page.locator('[data-node-id="tpl-7"]')).toBeVisible();
});

test("@smoke edits and previews a secure Teleport action", async ({ page }) => {
  const consoleErrors = collectConsoleErrors(page);

  await page.goto("/");
  await expect(page).toHaveTitle(
    "Free Roblox GUI Maker with AI | Visual Editor, Luau & .rbxmx Export"
  );
  await expect(page.locator('meta[name="description"]')).toHaveAttribute(
    "content",
    /real editable ScreenGui instances|Studio \.rbxmx models/
  );
  await expect(
    page.getByRole("heading", { level: 1, name: "Free Roblox GUI Maker with AI" })
  ).toBeVisible();
  await expect(
    page.getByRole("button", { name: "Generate GUI" })
  ).toBeVisible();
  for (const heading of [
    "Responsive Layout",
    "Interaction Preview",
    "Server-Safe Actions",
    "Luau, ZIP & .rbxmx",
  ]) {
    await expect(
      page.getByRole("heading", { level: 2, name: heading })
    ).toBeVisible();
  }
  const structuredData = (
    await page.locator('script[type="application/ld+json"]').allTextContents()
  ).map(
    (value) =>
      JSON.parse(value) as { "@type": string; [key: string]: unknown }
  );
  const webAppSchema = structuredData.find(
    (value) => value["@type"] === "SoftwareApplication"
  );
  expect(JSON.stringify(webAppSchema)).toContain(
    "browser-local ZIP project export"
  );
  expect(JSON.stringify(webAppSchema)).toContain(
    "Server handlers for RemoteEvent and Teleport actions"
  );
  expect(JSON.stringify(webAppSchema)).toContain(
    "AI-generated GUI starting points"
  );
  const faq = page.getByRole("region", {
    name: "Frequently asked questions",
  });
  await expect(faq.locator("summary")).toHaveCount(10);
  await faq
    .getByText("How is this different from AI image generators?")
    .click();
  await expect(
    faq.getByText(/actual ScreenGui, Frame, TextLabel, and TextButton instances/)
  ).toBeVisible();
  await faq
    .getByText("Does the editor generate server scripts and game logic?")
    .click();
  await expect(
    faq.getByText(
      /Economy balance, Robux purchase verification via MarketplaceService/
    )
  ).toBeVisible();
  const faqSchema = structuredData.find(
    (value) => value["@type"] === "FAQPage"
  ) as {
    mainEntity?: Array<{
      name: string;
      acceptedAnswer: { text: string };
    }>;
  };
  expect(faqSchema.mainEntity).toHaveLength(10);
  expect(
    faqSchema.mainEntity?.find(
      (item) => item.name === "Is Roblox GUI Maker free to use?"
    )?.acceptedAnswer.text
  ).toBe(
    "Yes. The visual editor, AI scene starter, all 13 templates, the 512×512 Gamepass Icon Maker, and clean client + server Luau, JSON, and ZIP exports are free with no account required. Optional one-time Pro passes unlock native .rbxmx Studio model export and multi-screen UI Kit bundles."
  );

  await page.goto("/editor");
  await page.evaluate(() => window.localStorage.clear());
  await page.reload();

  await expect(page.getByLabel("Client Luau code")).toContainText(
    "-- Generated by Roblox GUI Maker"
  );
  const actionSelect = page.locator("select").filter({
    has: page.locator('option[value="teleport"]'),
  });
  await actionSelect.selectOption("teleport");

  const placeId = page.getByRole("textbox", {
    name: "Destination Place ID",
  });
  await placeId.fill("12345678901234");
  await expect(page.getByLabel("Client Luau code")).toContainText(
    'teleportRequest:FireServer("12345678901234")'
  );

  await page.getByRole("tab", { name: "Server" }).click();
  await expect(page.getByLabel("Server Luau code")).toContainText(
    '["12345678901234"] = true'
  );
  await expect(page.getByLabel("Server Luau code")).toContainText(
    "TeleportService:TeleportAsync(numericPlaceId, { player })"
  );

  await placeId.fill("01");
  await expect(page.getByText("Place ID cannot start with zero.")).toBeVisible();
  await expect(page.getByLabel("Server Luau code")).toContainText(
    '["12345678901234"] = true'
  );
  await expect(page.getByLabel("Server Luau code")).not.toContainText(
    '["01"] = true'
  );

  await placeId.fill("456");
  await page.getByRole("button", { name: "Preview" }).click();
  await page.locator('[data-node-id="play"]').click();
  await expect(page.getByRole("status")).toHaveText(
    "Teleport to Place 456. Preview does not run live teleports."
  );

  expect(
    await page.evaluate(() => ({
      innerWidth: window.innerWidth,
      scrollWidth: document.documentElement.scrollWidth,
    }))
  ).toEqual({ innerWidth: 1280, scrollWidth: 1280 });
  expect(consoleErrors).toEqual([]);
});
