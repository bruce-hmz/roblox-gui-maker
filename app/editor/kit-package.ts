// ZIP bundling for Roblox Studio deliverables: a native .rbxmx bundle for a
// single scene, a full pro package per UI kit (unified rbxmx, per-screen files,
// server stub, scenes and 512x512 gamepass icons), and the all-icons pack.

import { strToU8, zipSync } from "fflate";
import type { SceneNode } from "./catalog";
import {
  GAMEPASS_ICON_PRESETS,
  kitGamepassIcons,
  renderGamepassIconSvg,
  type GamepassIconSpec,
} from "./gamepass-icons";
import { kitScene, KITS, type Kit } from "./kits";
import { serializeSceneDocument } from "./persistence";
import { kitToRbxmx, rbxmxFilename, sceneToRbxmx } from "./rbxmx";
import { generateLuau } from "./scene";
import { generateServerLuau } from "./server-luau";
import { getTemplate } from "./templates";

export type StudioRbxmxBundle = {
  filename: string;
  rbxmxFilename: string;
  rbxmxXml: string;
  bytes: Uint8Array;
};

type KitProPackage = { filename: string; bytes: Uint8Array };
type IconPackZip = { filename: string; bytes: Uint8Array };

function studioImportGuide(baseName: string, hasServerCode: boolean): string {
  const serverStep = hasServerCode
    ? "5. For RemoteEvent/teleport buttons, paste `roblox-gui.server.lua` into a\n   Script in ServerScriptService so the server side exists.\n"
    : "";

  return `# Roblox GUI Maker — Studio import (.rbxmx)

1. Open your experience in Roblox Studio.
2. In the Explorer, right-click **StarterGui** and choose **Insert from File...**
3. Select \`${baseName}.rbxmx\` — the ScreenGui appears immediately.
4. Press Play to see it live. Buttons already work (visibility, tweens,
   RemoteEvents, teleports) via the LocalScript embedded in the model.
${serverStep}
Prefer a runtime-built GUI instead? Paste \`roblox-gui.client.lua\` into a
LocalScript in StarterGui. Keep \`project.json\` if you want to re-import this
project into Roblox GUI Maker.
`;
}

export function createStudioRbxmxZip(
  scene: SceneNode[],
  clientCode: string,
  serverCode: string | null
): StudioRbxmxBundle {
  const rbxmxXml = sceneToRbxmx(scene);
  const rbxmxName = rbxmxFilename(scene);
  const baseName = rbxmxName.replace(/\.rbxmx$/, "");

  const files: Record<string, Uint8Array> = {
    [rbxmxName]: strToU8(rbxmxXml),
    "roblox-gui.client.lua": strToU8(clientCode),
    "project.json": strToU8(serializeSceneDocument(scene)),
    "STUDIO-IMPORT.md": strToU8(studioImportGuide(baseName, serverCode !== null)),
  };
  if (serverCode !== null) {
    files["roblox-gui.server.lua"] = strToU8(serverCode);
  }

  return {
    filename: `${baseName}.zip`,
    rbxmxFilename: rbxmxName,
    rbxmxXml,
    bytes: zipSync(files),
  };
}

function kitServerFileContent(kit: Kit, serverSections: string[]): string {
  const marketplaceStarter = [
    "-- ---------------------------------------------------------------------------",
    "-- Marketplace starter template — uncomment and wire your pass / product IDs:",
    '-- local MarketplaceService = game:GetService("MarketplaceService")',
    "-- MarketplaceService.ProcessReceipt:Connect(function(receiptInfo)",
    "-- \t-- Look up receiptInfo.PlayerId + receiptInfo.ProductId, grant the perk,",
    "-- \t-- persist the purchase, then confirm it:",
    "-- \treturn Enum.ProductPurchaseDecision.PurchaseGranted",
    "-- end)",
    "-- MarketplaceService.PromptGamePassPurchaseFinished:Connect(function(player, gamePassId, wasPurchased)",
    "-- \tif wasPurchased then",
    "-- \t\t-- Grant the pass perk to `player` here.",
    "-- \tend",
    "-- end)",
  ].join("\n");

  const sections =
    serverSections.length > 0
      ? serverSections.join("\n\n") + "\n\n"
      : "-- No screen in this kit generates server Luau yet.\n\n";

  return [
    `-- Generated by Roblox GUI Maker — ${kit.name} server stubs`,
    "-- Place this Script in ServerScriptService.",
    "",
    sections,
    marketplaceStarter,
  ].join("\n");
}

function kitReadme(kit: Kit): string {
  return `# ${kit.name} — Roblox Studio install

## Quick start (all ${kit.screens.length} screens)

1. Open your experience in Roblox Studio.
2. Right-click **StarterGui** in the Explorer → **Insert from File...**
3. Pick \`${kit.slug}-complete.rbxmx\`.
4. Press **Play** — the main menu shows; switch screens with the tabs at the
   top of the screen (or press the number keys). HUD screens stay on in every
   page.

## À la carte

\`screens/NN-<template>.rbxmx\` contains one screen each — import only what you
need. \`screens/NN-<template>.client.lua\` is the runtime-built variant of the
same screen if you prefer building the GUI from a script.

## Monetization

- \`icons/*.svg\` are 512x512 Gamepass / shop badge icons matched to this kit's
  genre and theme, ready to upload as pass icons (convert to PNG if your
  pipeline requires it).
- \`server/${kit.slug}.server.lua\` ships RemoteEvent stubs plus a commented
  MarketplaceService starter (ProcessReceipt / PromptGamePassPurchaseFinished).

## Re-editing

\`scenes/*.json\` re-import into Roblox GUI Maker to keep editing the kit.
`;
}

export function createKitProPackage(kit: Kit): KitProPackage {
  if (kit.screens.length === 0) {
    throw new Error(`createKitProPackage: kit "${kit.slug}" has no screens`);
  }

  const files: Record<string, Uint8Array> = {
    [`${kit.slug}-complete.rbxmx`]: strToU8(kitToRbxmx(kit)),
  };

  const serverSections: string[] = [];
  kit.screens.forEach((screen, index) => {
    const screenScene = kitScene(kit, screen.template);
    if (!screenScene) {
      throw new Error(
        `createKitProPackage: kit "${kit.slug}" screen template "${screen.template}" with theme "${kit.theme}" could not be resolved`
      );
    }
    const ordinal = String(index + 1).padStart(2, "0");
    const fileBase = `${ordinal}-${screen.template}`;
    files[`screens/${fileBase}.rbxmx`] = strToU8(sceneToRbxmx(screenScene));
    files[`screens/${fileBase}.client.lua`] = strToU8(generateLuau(screenScene));
    files[`scenes/${fileBase}.json`] = strToU8(serializeSceneDocument(screenScene));

    const serverCode = generateServerLuau(screenScene);
    if (serverCode !== null) {
      serverSections.push(
        `-- Screen ${ordinal} (${screen.template})\n${serverCode}`
      );
    }
  });

  files[`server/${kit.slug}.server.lua`] = strToU8(
    kitServerFileContent(kit, serverSections)
  );
  for (const icon of kitGamepassIcons(kit.slug)) {
    files[`icons/${icon.id}.svg`] = strToU8(renderGamepassIconSvg(icon));
  }
  files["README-STUDIO.md"] = strToU8(kitReadme(kit));

  return {
    filename: `${kit.slug}-pro.zip`,
    bytes: zipSync(files),
  };
}

export function createAllIconsPackZip(): IconPackZip {
  const specs: GamepassIconSpec[] = [];
  const seenIds = new Set<string>();
  const addUniqueIcon = (icon: GamepassIconSpec) => {
    if (seenIds.has(icon.id)) {
      throw new Error(`createAllIconsPackZip: duplicate icon id "${icon.id}"`);
    }
    seenIds.add(icon.id);
    specs.push(icon);
  };
  GAMEPASS_ICON_PRESETS.forEach(addUniqueIcon);
  KITS.forEach((kit) => kitGamepassIcons(kit.slug).forEach(addUniqueIcon));

  const passShopTemplate = getTemplate("game-pass-shop");
  if (!passShopTemplate) {
    throw new Error('createAllIconsPackZip: template "game-pass-shop" is missing');
  }

  const files: Record<string, Uint8Array> = {
    "game-pass-shop.rbxmx": strToU8(sceneToRbxmx(passShopTemplate.scene)),
  };
  for (const icon of specs) {
    files[`icons/${icon.id}.svg`] = strToU8(renderGamepassIconSvg(icon));
  }

  return {
    filename: "roblox-gamepass-icon-pack-pro.zip",
    bytes: zipSync(files),
  };
}
