// Export & interaction validation over scenes captured by the production
// evaluation (scripts/eval-ai-gui.mjs writes them to $SCENES_DIR). Runs the
// REAL deterministic compilers against every captured scene — the gate's
// "Export Success Rate = 100%" is proven here, not assumed. Skips silently
// when no captured scenes exist (e.g. CI) so it never blocks unrelated runs.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import type { SceneNode } from "../catalog";
import { sanitizeScene } from "../persistence";
import { generateLuau } from "../scene";
import { generateServerLuau } from "../server-luau";
import { remoteEventButtons } from "../remote-events";

const SCENES_DIR =
  process.env.SCENES_DIR ?? "/tmp/rgm-eval-scenes";

type Captured = {
  prompt: string;
  expected: string;
  meta?: { screenType?: string; fallbackUsed?: boolean | string };
  scene: SceneNode[];
};

const captured: Captured[] = existsSync(SCENES_DIR)
  ? readdirSync(SCENES_DIR)
      .filter((f) => f.startsWith("scene-") && f.endsWith(".json"))
      .sort()
      .map((f) => JSON.parse(readFileSync(join(SCENES_DIR, f), "utf8")) as Captured)
  : [];

describe.skipIf(captured.length === 0)(
  `eval scenes export & interaction validation (${captured.length} captured)`,
  () => {
    it("every captured scene exports clean client Luau", () => {
      for (const item of captured) {
        const scene = sanitizeScene(item.scene);
        expect(scene, item.prompt).not.toBeNull();
        const client = generateLuau(scene!);
        expect(client, item.prompt).toContain("-- Generated by Roblox GUI Maker");
        expect(client, item.prompt).toContain('Instance.new("ScreenGui")');
        // Forbidden constructs must never appear in generated code.
        expect(client, item.prompt).not.toContain("loadstring");
        expect(client, item.prompt).not.toMatch(/require\s*\(/);
      }
    });

    it("every captured scene with RemoteEvents exports a server allow-list", () => {
      for (const item of captured) {
        const scene = sanitizeScene(item.scene)!;
        for (const button of remoteEventButtons(scene)) {
          expect(button.action.eventName, item.prompt).toMatch(/^[A-Za-z0-9_]+$/);
        }
        const server = generateServerLuau(scene);
        if (remoteEventButtons(scene).length > 0) {
          expect(server, item.prompt).toContain("ServerScriptService");
          for (const button of remoteEventButtons(scene)) {
            expect(server, item.prompt).toContain(`"${button.action.eventName}"`);
            expect(server, item.prompt).toContain(`"${button.action.argument}"`);
          }
        }
      }
    });

    it("all show/hide/toggle action targets are valid frames", () => {
      for (const item of captured) {
        const scene = sanitizeScene(item.scene)!;
        const ids = new Set(scene.map((n) => n.id));
        for (const node of scene) {
          const action = node.action;
          if (!action) continue;
          const targetId = "targetId" in action ? action.targetId : undefined;
          if (targetId) {
            expect(ids.has(targetId), `${item.prompt} → ${node.name}`).toBe(true);
            const target = scene.find((n) => n.id === targetId);
            expect(["Frame", "ScrollingFrame"], `${item.prompt} → ${node.name}`).toContain(
              target?.cls
            );
          }
        }
      }
    });
  }
);
